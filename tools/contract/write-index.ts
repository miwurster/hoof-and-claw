// Writes the barrel files of `contract/`: one for the game's types, one for the test controls' types.
import { mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const HEADER = "// This file was generated by tools/contract/write-index.ts. Do not edit this file manually.\n";

function writeIndex(dir: string): void {
  mkdirSync(dir, { recursive: true });

  const modules = readdirSync(dir)
    .filter((name) => name.endsWith(".ts") && name !== "index.ts")
    .toSorted();

  const lines = modules.map((name) => `export type * from "./${name.slice(0, -".ts".length)}";`);
  const body = lines.length === 0 ? "export {};" : lines.join("\n");

  writeFileSync(join(dir, "index.ts"), `${HEADER}${body}\n`);
}

const root = join(import.meta.dirname, "..", "..", "contract", "src");

writeIndex(root);

writeIndex(join(root, "test-controls"));
